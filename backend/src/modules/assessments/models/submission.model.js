import mongoose from 'mongoose';
import { ASSESSMENT_STATUSES } from '../../../../../../packages/shared-constants/index.js';

const SubmissionSchema = new mongoose.Schema(
  {
    assessment: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Assessment',
      required: true
    },
    student: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    status: {
      type: String,
      enum: Object.values(ASSESSMENT_STATUSES),
      default: ASSESSMENT_STATUSES.IN_PROGRESS
    },
    startTime: {
      type: Date,
      default: Date.now
    },
    endTime: Date,
    timeTakenSeconds: Number,
    answers: [{
      questionId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Question'
      },
      selectedOptions: [String], // For MCQs
      codeSubmitted: String, // For coding questions
      language: String, // For coding questions
      isCorrect: Boolean,
      marksObtained: Number
    }],
    totalMarksObtained: {
      type: Number,
      default: 0
    },
    scorePercentage: Number,
    isPassed: Boolean,
    aiFeedback: String, // Feedback generated by Gemini after evaluation
    proctoringLogs: [{
      eventType: String, // e.g., 'TAB_SWITCH', 'MULTIPLE_FACES', 'NO_FACE'
      timestamp: Date,
      snapshotUrl: String
    }]
  },
  { timestamps: true }
);

SubmissionSchema.index({ assessment: 1, student: 1 }, { unique: true });

export default mongoose.models.Submission || mongoose.model('Submission', SubmissionSchema);
